"""CSV and HTML reports of one run or of a project's run history, stored in object storage.

HTML reports are self-contained (inline styles, no script, every value escaped), so they
can be attached to a ticket or opened offline.
"""

from __future__ import annotations

import csv
import html
import io
import uuid
from collections.abc import Sequence
from datetime import datetime

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from testforge.audit.service import audit
from testforge.core.container import Container
from testforge.core.errors import NotFoundError
from testforge.coverage import service as coverage
from testforge.projects.access import Principal
from testforge.reports.models import Report
from testforge.runs import service as runs
from testforge.runs.models import TestCaseResult, TestRun

CONTENT_TYPES = {"csv": "text/csv; charset=utf-8", "html": "text/html; charset=utf-8"}
CSV_INJECTION = ("=", "+", "-", "@", "\t", "\r")


def _cell(value: object) -> str:
    """A CSV cell that a spreadsheet will not evaluate as a formula."""
    text = "" if value is None else str(value)
    return "'" + text if text.startswith(CSV_INJECTION) else text


def _csv(rows: list[list[object]]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    for row in rows:
        w.writerow([_cell(v) for v in row])
    return buf.getvalue().encode()


def _when(dt: datetime | None) -> str:
    return dt.strftime("%Y-%m-%d %H:%M UTC") if dt else ""


STYLE = """
body{font:14px/1.5 system-ui,sans-serif;margin:32px;color:#1c1b22;background:#fff}
h1{font-size:22px;margin:0 0 4px}h2{font-size:16px;margin:28px 0 8px}
.muted{color:#6b6880}table{border-collapse:collapse;width:100%}
td,th{padding:6px 10px;text-align:left;vertical-align:top}
tr:nth-child(even) td{background:#f6f5fa}th{background:#ecebf3}
.passed{color:#11795a}.failed,.error,.limit_exceeded{color:#b42318}
pre{white-space:pre-wrap;margin:0;font:12px ui-monospace,monospace}
"""


def _page(title: str, subtitle: str, body: str) -> bytes:
    return (
        "<!doctype html><html><head><meta charset='utf-8'>"
        f"<title>{html.escape(title)}</title><style>{STYLE}</style></head><body>"
        f"<h1>{html.escape(title)}</h1><p class='muted'>{html.escape(subtitle)}</p>{body}"
        "<p class='muted'>Generated by Euron Open TestForge.</p></body></html>"
    ).encode()


def _table(head: list[str], rows: list[list[object]], cls: int | None = None) -> str:
    out = ["<table><tr>" + "".join(f"<th>{html.escape(h)}</th>" for h in head) + "</tr>"]
    for row in rows:
        cells = []
        for i, v in enumerate(row):
            text = html.escape("" if v is None else str(v))
            klass = f" class='{html.escape(str(v))}'" if cls is not None and i == cls else ""
            cells.append(f"<td{klass}>{text}</td>")
        out.append("<tr>" + "".join(cells) + "</tr>")
    return "".join(out) + "</table>"


async def _run_report(
    session: AsyncSession, run: TestRun, fmt: str, project_name: str
) -> tuple[str, bytes]:
    cases: Sequence[TestCaseResult] = await runs.cases(session, run.id)
    cov = await coverage.for_run(session, run.id)
    title = f"{project_name}: run {str(run.id)[:8]} {run.status}"
    if fmt == "csv":
        rows: list[list[object]] = [
            ["test", "file", "outcome", "duration_ms", "expected", "actual", "explanation"]
        ]
        for c in cases:
            f = c.failure or {}
            rows.append(
                [
                    c.name,
                    c.file,
                    c.outcome,
                    round(c.duration_ms, 2),
                    f.get("expected"),
                    f.get("actual"),
                    f.get("explanation") or c.message,
                ]
            )
        return title, _csv(rows)
    summary = _table(
        [
            "Status",
            "Passed",
            "Failed",
            "Errors",
            "Coverage",
            "CPU",
            "Wall",
            "Peak memory",
            "Limit crossed",
        ],
        [
            [
                run.status,
                run.passed,
                run.failed,
                run.errors,
                f"{run.coverage_percent}%" if run.coverage_percent is not None else "not measured",
                f"{(run.cpu_ms or 0) / 1000:.2f} s",
                f"{(run.wall_ms or 0) / 1000:.2f} s",
                f"{(run.memory_kb or 0) // 1024} MB",
                run.limit_exceeded or "none",
            ]
        ],
        cls=0,
    )
    failures = [
        [c.name, c.outcome, (c.failure or {}).get("explanation") or c.message]
        for c in cases
        if c.outcome in ("failed", "error")
    ]
    body = "<h2>Summary</h2>" + summary
    if failures:
        body += "<h2>Failures, explained</h2>" + _table(
            ["Test", "Outcome", "Explanation"], failures, cls=1
        )
    body += "<h2>Every test</h2>" + _table(
        ["Test", "File", "Outcome", "ms"],
        [[c.name, c.file, c.outcome, round(c.duration_ms, 1)] for c in cases],
        cls=2,
    )
    if cov is not None:
        body += "<h2>Coverage by file</h2>" + _table(
            ["File", "Lines", "Covered", "%"],
            [[f["path"], f["lines_total"], f["lines_covered"], f["percent"]] for f in cov.files],
        )
    who = run.actor or "TestForge"
    subtitle = f"{run.kind} tests, {run.framework}, started {_when(run.started_at)} by {who}"
    return title, _page(title, subtitle, body)


async def _project_report(
    session: AsyncSession, project_id: uuid.UUID, fmt: str, project_name: str
) -> tuple[str, bytes]:
    history = await runs.list_runs(session, project_id, limit=500)
    title = f"{project_name}: test history"
    rows: list[list[object]] = [
        [
            _when(r.created_at),
            str(r.id),
            r.kind,
            r.status,
            r.passed,
            r.failed,
            r.errors,
            r.coverage_percent,
            r.limit_exceeded,
            r.actor,
        ]
        for r in history
    ]
    head = [
        "started",
        "run",
        "kind",
        "status",
        "passed",
        "failed",
        "errors",
        "coverage",
        "limit",
        "by",
    ]
    if fmt == "csv":
        return title, _csv([list(head), *rows])
    return title, _page(title, f"{len(history)} runs, newest first", _table(head, rows, cls=3))


async def create(
    container: Container,
    session: AsyncSession,
    p: Principal,
    scope: str,
    fmt: str,
    run_id: uuid.UUID | None,
) -> Report:
    if scope == "run":
        if run_id is None:
            raise NotFoundError("Choose the run to report on")
        run = await runs.get(session, p.project_id, run_id)
        title, data = await _run_report(session, run, fmt, p.project.name)
    else:
        title, data = await _project_report(session, p.project_id, fmt, p.project.name)
    report = Report(
        project_id=p.project_id,
        scope=scope,
        run_id=run_id if scope == "run" else None,
        format=fmt,
        title=title[:300],
        object_key="",
        size_bytes=len(data),
        created_by=p.user_id,
    )
    report.id = uuid.uuid4()
    report.object_key = f"reports/{p.project_id}/{report.id}.{fmt}"
    await container.storage.put(report.object_key, data, CONTENT_TYPES[fmt])
    session.add(report)
    audit(
        session,
        p.actor,
        "report.created",
        "report",
        report.id,
        scope=scope,
        format=fmt,
        **p.audit_scope(),
    )
    await session.commit()
    await session.refresh(report)
    return report


async def list_reports(session: AsyncSession, project_id: uuid.UUID) -> Sequence[Report]:
    return (
        await session.scalars(
            select(Report)
            .where(Report.project_id == project_id)
            .order_by(Report.created_at.desc())
            .limit(100)
        )
    ).all()


async def get(session: AsyncSession, project_id: uuid.UUID, report_id: uuid.UUID) -> Report:
    report = await session.scalar(
        select(Report).where(Report.id == report_id, Report.project_id == project_id)
    )
    if report is None:
        raise NotFoundError("Report not found")
    return report
