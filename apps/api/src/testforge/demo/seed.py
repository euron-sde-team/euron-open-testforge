def _zip(name: str, extra: dict[str, str] | None = None) -> bytes:
    buf = io.BytesIO()
    root = PROJECTS / name
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(root.rglob("*")):
            if p.is_file() and "__pycache__" not in p.parts:
                zf.writestr(f"{name}/{p.relative_to(root)}", p.read_bytes())
        for path, text in (extra or {}).items():
            zf.writestr(f"{name}/{path}", text)
    return buf.getvalue()


async def _people(db: Database, password: str) -> None:
    """The demo organization and its people, fresh each time."""
    async with db.sessionmaker() as session:
        org = await session.scalar(select(Organization).where(Organization.name == ORG))
        if org is not None:
            await session.execute(delete(Project).where(Project.org_id == org.id))
            await session.delete(org)
            await session.commit()
        settings = await session.get(InstanceSettings, 1)
        if settings is None:
            session.add(InstanceSettings(id=1, site_name="TestForge"))
        owner: User | None = None
        for email, name, org_role, _ in PEOPLE:
            user = await session.scalar(select(User).where(User.email == email))
            if user is None:
                user = User(
                    email=email,
                    name=name,
                    role="admin" if org_role == "owner" else "user",
                    password_hash="",
                )
                session.add(user)
            user.password_hash = hash_password(password)
            user.disabled = False
            user.failed_logins = 0
            user.locked_until = None
            await session.flush()
            if owner is None:
                owner = user
                new = await orgs.create_for(session, user, ORG, Actor(user.id, user.email, "admin"))
                org_id = new.id
            else:
                session.add(OrgMember(org_id=org_id, user_id=user.id, role=org_role))
        await session.commit()


class Api:
    def __init__(self, base: str) -> None:
        self.http = httpx.AsyncClient(base_url=base, timeout=600, headers={"x-tf-csrf": "1"})

    async def login(self, email: str, password: str) -> None:
        resp = await self.http.post(
            "/api/v1/auth/login", json={"email": email, "password": password}
        )
        resp.raise_for_status()
        self.http.headers["authorization"] = f"Bearer {resp.json()['session_token']}"

    async def call(self, method: str, path: str, json: Any = None, **kw: Any) -> Any:
        resp = await self.http.request(method, path, json=json, **kw)
        if resp.status_code >= 400:
            raise RuntimeError(f"{method} {path}: {resp.status_code} {resp.text[:400]}")
        return resp.json() if resp.content else None


async def _shop(api: Api, org_id: str, mock_url: str) -> None:
    p = (
        await api.call(
            "POST",
            "/api/v1/projects",
            {
                "org_id": org_id,
                "name": "Shop API",
                "description": "The storefront's FastAPI service: pricing, carts and inventory.",
            },
        )
    )["id"]
    base = f"/api/v1/projects/{p}"
    await api.call("POST", f"{base}/providers", {"name": "mock", "kind": "mock"})
    await api.call(
        "POST",
        f"{base}/providers",
        {
            "name": "claude",
            "kind": "anthropic",
            "base_url": f"{mock_url}/anthropic",
            "api_key": "demo-key-not-real",
            "model": "claude-sonnet-4-5",
            "enabled": False,
        },
    )
    for email, _, _, role in PEOPLE[1:]:
        await api.call("POST", f"{base}/members", {"email": email, "role": role})
    await api.call("PATCH", base, {"github_repo": "euron-demo/python-shop"})
    imp = await api.call(
        "POST", f"{base}/imports/github", {"repo": "euron-demo/python-shop"}, params={"wait": 120}
    )
    print(
        f"  Shop API: imported {imp['label']} at {imp['commit_sha'][:7]}, {imp['summary']['units']} units"
    )
    # 1. The project's own suite: low coverage, the starting point of the trend.
    await api.call("POST", f"{base}/runs", {"kind": "project"}, params={"wait": 300})
    # 2. Unit, edge and negative tests from the analyzed source.
    gen = await api.call(
        "POST",
        f"{base}/tests/generate",
        {"kinds": ["unit", "edge", "negative"]},
        params={"wait": 300},
    )
    tests = await api.call("GET", f"{base}/tests", params={"generation_id": gen["id"]})
    keep = [t["id"] for t in tests if "split_bill" not in t["name"] or "examples" in t["name"]]
    await api.call("POST", f"{base}/tests/review", {"ids": keep, "status": "accepted"})
    run = await api.call("POST", f"{base}/runs", {"kind": "generated"}, params={"wait": 300})
    print(
        f"  Shop API: {gen['accepted_count']} tests generated, {gen['rejected_count']} refused; run {run['status']} ({run['passed']} passed, {run['failed']} failed)"
    )
    # 3. API tests from the OpenAPI document.
    spec = await api.call(
        "POST", f"{base}/specs", {"document": (PROJECTS / "python-shop-openapi.json").read_text()}
    )
    api_gen = await api.call(
        "POST",
        f"{base}/tests/generate",
        {"kinds": ["api"], "spec_id": spec["id"]},
        params={"wait": 300},
    )
    api_tests = await api.call("GET", f"{base}/tests", params={"generation_id": api_gen["id"]})
    await api.call(
        "POST", f"{base}/tests/review", {"ids": [t["id"] for t in api_tests], "status": "accepted"}
    )
    full = await api.call("POST", f"{base}/runs", {"kind": "all"}, params={"wait": 300})
    print(
        f"  Shop API: {len(api_tests)} API tests for {spec['operation_count']} operations; full run {full['status']}, coverage {full['coverage_percent']}%"
    )
    # 4. A pull request, scoped.
    pull = await api.call("POST", f"{base}/pulls", {"number": 12}, params={"wait": 120})
    await api.call(
        "POST",
        f"{base}/tests/generate",
        {"kinds": ["unit", "negative"], "pull_id": pull["id"]},
        params={"wait": 300},
    )
    print(f"  Shop API: pull request #12 touches {len(pull['scoped_unit_ids'])} units")
    # 5. CI wiring and exports.
    await api.call(
        "POST", f"{base}/api-keys", {"name": "GitHub Actions", "scopes": ["read", "execute"]}
    )
    await api.call(
        "POST",
        f"{base}/webhooks",
        {
            "name": "Team chat",
            "url": f"{mock_url}/_mock/hooks/team-chat",
            "events": ["run.finished"],
        },
    )
    await api.call("POST", f"{base}/github/webhook-secret")
    await api.call(
        "POST", f"{base}/reports", {"scope": "run", "run_id": run["id"], "format": "html"}
    )
    await api.call("POST", f"{base}/reports", {"scope": "project", "format": "csv"})


