async def _sandbox_checks(api: Api, org_id: str) -> None:
    p = (
        await api.call(
            "POST",
            "/api/v1/projects",
            {
                "org_id": org_id,
                "name": "Sandbox checks",
                "description": "An uploaded project whose own tests try to leave the sandbox.",
            },
        )
    )["id"]
    base = f"/api/v1/projects/{p}"
    await api.call("POST", f"{base}/providers", {"name": "mock", "kind": "mock"})
    data = _zip(
        "python-shop",
        {"tests/test_network.py": NETWORK_PROBE, "tests/test_escape.py": ESCAPE_PROBE},
    )
    await api.call(
        "POST",
        f"{base}/imports/zip",
        files={"file": ("shop-with-probes.zip", data, "application/zip")},
        params={"wait": 120},
    )
    run = await api.call("POST", f"{base}/runs", {"kind": "project"}, params={"wait": 300})
    await api.call("PATCH", base, {"run_wall_s": 8})
    data = _zip("python-shop", {"tests/test_hang.py": HANG_PROBE})
    await api.call(
        "POST",
        f"{base}/imports/zip",
        files={"file": ("shop-hangs.zip", data, "application/zip")},
        params={"wait": 120},
    )
    stopped = await api.call("POST", f"{base}/runs", {"kind": "project"}, params={"wait": 120})
    print(
        f"  Sandbox checks: probes run {run['status']} ({run['failed']} refused), hanging suite {stopped['status']} at {stopped['limit_exceeded']}"
    )


async def run() -> None:
    settings = get_settings()
    password = os.environ.get("TESTFORGE_DEMO_PASSWORD", "")
    api_url = os.environ.get("TESTFORGE_DEMO_API_URL", "http://api:8080")
    mock_url = os.environ.get("TESTFORGE_DEMO_MOCK_URL", "http://mockai:5650")
    if not password:
        raise SystemExit("TESTFORGE_DEMO_PASSWORD is not set (make env writes it)")
    import_all_models()
    db = Database(settings.database_url, pool_size=2, max_overflow=0)
    try:
        await _people(db, password)
    finally:
        await db.dispose()
    api = Api(api_url)
    try:
        await api.login(PEOPLE[0][0], password)
        org_id = next(o["id"] for o in await api.call("GET", "/api/v1/orgs") if o["name"] == ORG)
        print("Seeding the demo (real imports, generations and sandboxed runs; a few minutes):")
        await _shop(api, org_id, mock_url)
        await _toolkit(api, org_id)
        await _sandbox_checks(api, org_id)
    finally:
        await api.http.aclose()
    print("\nDemo ready. Sign in with any of:")
    for email, name, _, role in PEOPLE:
        print(f"  {email:<28} {name:<12} {role}")


if __name__ == "__main__":
    asyncio.run(run())
