"""``make demo``: a working TestForge with real data behind every screen.

People are created in the database (the instance has open sign-up off); everything else
goes through the running API exactly as a developer would use it, so every import is
really analyzed by the worker, every test is really generated by the deterministic mock
model and checked, and every run really executes in the sandbox:

* "Shop API" (Python, FastAPI): the demo repository imported from the mock GitHub, its
  own suite run, unit, edge and negative tests generated and accepted, a run that fails on
  a real bug in ``split_bill`` (explained), API tests from its OpenAPI document, pull
  request #12 imported and scoped, a CI API key and a webhook, reports.
* "Web Toolkit" (TypeScript): imported, tests generated and run with Vitest, pull request
  #4 scoped.
* "Sandbox checks": an uploaded project whose own tests try to reach the network, read
  outside their workspace and run forever, so the run history shows refusals and a limit.

Run it again at any time: it removes the demo organization and starts over.
"""

